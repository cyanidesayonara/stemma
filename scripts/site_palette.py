"""Generate site/palette.css from the app's theme colours.

The website wears the app's two themes: the dark and light palettes and the
per-stem colours in ``src/ui/styles.py``. This script writes them out as CSS
custom properties, so the site cannot drift from the app.
``tests/test_site.py`` fails when ``site/palette.css`` is stale.

    python scripts/site_palette.py           rewrites site/palette.css
    python scripts/site_palette.py --check   exits 1 if it is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.ui.styles import (  # noqa: E402
    DARK_COLORS,
    LIGHT_COLORS,
    STEM_COLORS_DARK,
    STEM_COLORS_LIGHT,
)

PALETTE_CSS = ROOT / "site" / "palette.css"


def _declarations(colors: dict[str, str], stems: dict[str, str]) -> list[str]:
    lines = [
        f"  --{name.replace('_', '-')}: {value};"
        for name, value in colors.items()
    ]
    lines += [f"  --stem-{name}: {value};" for name, value in stems.items()]
    return lines


def render() -> str:
    """Return the palette stylesheet text."""
    dark = _declarations(DARK_COLORS, STEM_COLORS_DARK)
    light = _declarations(LIGHT_COLORS, STEM_COLORS_LIGHT)
    indented_light = ["  " + line for line in light]
    parts = [
        "/* Generated by scripts/site_palette.py from src/ui/styles.py. Do not",
        "   edit: change the colours there and rerun it. Dark is the default,",
        "   light follows the system unless the page's theme toggle picks one. */",
        ":root {",
        "  color-scheme: dark;",
        *dark,
        "}",
        "",
        "@media (prefers-color-scheme: light) {",
        "  :root:not([data-theme=\"dark\"]) {",
        "    color-scheme: light;",
        *indented_light,
        "  }",
        "}",
        "",
        ":root[data-theme=\"light\"] {",
        "  color-scheme: light;",
        *light,
        "}",
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = PALETTE_CSS.read_text(encoding="utf-8") if PALETTE_CSS.exists() else ""
        if current != text:
            print("site/palette.css is stale; run scripts/site_palette.py",
                  file=sys.stderr)
            return 1
        print("site/palette.css is up to date")
        return 0
    PALETTE_CSS.parent.mkdir(parents=True, exist_ok=True)
    PALETTE_CSS.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {PALETTE_CSS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
